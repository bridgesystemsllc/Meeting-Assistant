/**
 * Email Service for Worker
 */

import nodemailer from 'nodemailer';
import type { MeetingAnalysis } from '@meeting-assistant/shared';
import { logger } from '../lib/logger.js';

interface MeetingInfo {
  id: string;
  title: string;
  started_at: string | null;
  duration_seconds: number | null;
}

interface RecapEmailData {
  meeting: MeetingInfo;
  analysis: MeetingAnalysis;
  ownerEmail: string;
  ownerName?: string;
  ownerId?: string; // P3-2: Log user id, not email
  language?: string | null;
}

let transporter: nodemailer.Transporter | null = null;

function getTransporter(): nodemailer.Transporter {
  if (!transporter) {
    transporter = nodemailer.createTransport({
      host: process.env.SMTP_HOST,
      port: parseInt(process.env.SMTP_PORT || '587'),
      secure: false,
      auth: process.env.SMTP_USER ? {
        user: process.env.SMTP_USER,
        pass: process.env.SMTP_PASS,
      } : undefined,
    });
  }
  return transporter;
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

function formatDuration(seconds: number | null): string {
  if (!seconds) return 'Unknown duration';
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  return h > 0 ? `${h}h ${m}m` : `${m} minutes`;
}

export async function sendRecapEmail(data: RecapEmailData): Promise<boolean> {
  const { meeting, analysis, ownerEmail, language } = data;

  if (!process.env.SMTP_HOST) {
    logger.info({ meetingId: meeting.id }, 'SMTP not configured, skipping recap email');
    return false;
  }

  const subject = `📋 Meeting Notes: ${escapeHtml(meeting.title)}`;
  
  const actionItemsHtml = analysis.action_items.length > 0
    ? analysis.action_items.map(item => `
        <li style="margin-bottom: 8px;">
          <strong>${escapeHtml(item.task)}</strong><br/>
          <span style="color: #666; font-size: 13px;">
            Owner: ${escapeHtml(item.owner)} 
            ${item.due_date ? `| Due: ${escapeHtml(item.due_date)}` : ''}
            | Priority: ${item.priority}
          </span>
        </li>
      `).join('')
    : '<li style="color: #999;">No action items identified</li>';

  const html = `
<!DOCTYPE html>
<html>
<head><meta charset="utf-8"></head>
<body style="font-family: sans-serif; padding: 20px;">
  <h1>${escapeHtml(meeting.title)}</h1>
  <p>${meeting.started_at ? new Date(meeting.started_at).toLocaleDateString() : ''} 
     ${formatDuration(meeting.duration_seconds)} ${language ? `(${language.toUpperCase()})` : ''}</p>
  <h2>Summary</h2>
  <p>${escapeHtml(analysis.summary)}</p>
  <h2>Action Items</h2>
  <ul>${actionItemsHtml}</ul>
  <hr/>
  <p style="color: #999; font-size: 12px;">Generated by [PRODUCT NAME]</p>
</body>
</html>`;

  const text = `MEETING NOTES: ${meeting.title}\n\n${analysis.summary}\n\nAction Items:\n${
    analysis.action_items.map((item, i) => `${i + 1}. ${item.task} (${item.owner})`).join('\n')
  }`;

  try {
    const transport = getTransporter();
    
    await transport.sendMail({
      from: `[PRODUCT NAME] <${process.env.FROM_EMAIL || 'noreply@example.com'}>`,
      to: ownerEmail,
      subject,
      html,
      text,
    });

    // P3-2: Log user id, not email
    logger.info({ meetingId: meeting.id, ownerId: data.ownerId }, 'Recap email sent');
    return true;
  } catch (err) {
    logger.error({ meetingId: meeting.id, err }, 'Failed to send recap email');
    return false;
  }
}

export function setTransporter(t: nodemailer.Transporter | null): void {
  transporter = t;
}
